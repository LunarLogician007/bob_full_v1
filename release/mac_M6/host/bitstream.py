CLB_FF_D_SEL = FIELD["ff_d_sel"][0] - TILE_CLB_LO

NTILE = GRID_R * GRID_C
FABRIC_CFG_W = DEVICE["chain"]["width"]          # the WHOLE chain (3064 for K=6)
