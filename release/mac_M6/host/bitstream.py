"""
Bitstream generation for the 4x4 CLB fabric.

Every constant, field offset and pad position here is loaded from
tools/bob/device.json, generated by tools/bob/device.py - the single source of
truth. Set BOB_DEVICE_JSON to use another description (the K=4 tests do).
tests/test_device.py checks the description against hw/src/clb/clb_pkg.sv, and
sim/gen_vectors.py + the fabric testbench keep this engine honest against the RTL.

  Chain = ctrl tile (clock mode + divider) + 16 fabric tiles
  Tile  = CLB(2**K + 7) + connection box((K+2) muxes) + switch box(16 muxes)
          K=6: 71 + 40 + 80 = 191 bits; chain 8 + 16*191 = 3064 bits

Routing model
-------------
Every mux in a tile chooses from the same 20-entry source bus:

    0        const 0
    1        const 1
    2        this tile's CLB o
    3        this tile's CLB o5
    4..7     tracks arriving from the North
    8..11    tracks arriving from the East
    12..15   tracks arriving from the South
    16..19   tracks arriving from the West

The connection box has K LUT-input muxes plus the flip-flop's CE and SR muxes
(M4, UG474: CE/SR are routable). Tracks are point to point. Driving tile T's
switch box output in direction D on track t makes that signal arrive at T's
neighbour in direction D, on the opposite side, same track number:

    drive out_N[t]  ->  neighbour (r+1, c) sees it on in_S[t]
    drive out_E[t]  ->  neighbour (r, c+1) sees it on in_W[t]
    drive out_S[t]  ->  neighbour (r-1, c) sees it on in_N[t]
    drive out_W[t]  ->  neighbour (r, c-1) sees it on in_E[t]

The router is a breadth-first search over tiles, allocating one switch box mux
per hop. A mux already carrying the same signal is free to traverse again,
which is how fanout works without any special case.
"""

