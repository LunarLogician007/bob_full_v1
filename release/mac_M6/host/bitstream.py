def src_e(t): return _SRC[f"E{t}"]
def src_s(t): return _SRC[f"S{t}"]
def src_w(t): return _SRC[f"W{t}"]


SRC_OF_DIR = {DIR_N: src_n, DIR_E: src_e, DIR_S: src_s, DIR_W: src_w}
OPPOSITE = {DIR_N: DIR_S, DIR_S: DIR_N, DIR_E: DIR_W, DIR_W: DIR_E}
DELTA = {DIR_N: (1, 0), DIR_E: (0, 1), DIR_S: (-1, 0), DIR_W: (0, -1)}

TILE_CLB_LO, CLB_CFG_W = _group("clb")           # 0, 71  (K=6)
