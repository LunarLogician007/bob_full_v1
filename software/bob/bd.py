#!/usr/bin/env python3
"""
bd.py - block designs: blocks wired on a canvas, turned into a Verilog wrapper (M18).

Vivado's IP integrator, cut down to this fabric. A block design (<bd>.bd, JSON) holds

  blocks   instances of the project's own modules ("module") or of the IP cores in
           software/bob/ip/ ("ip"), each with its parameters and a canvas position
  wires    "src" -> "dst" endpoint pairs. An endpoint is <block>.<port>, optionally
           with a bit select: cnt.q, cnt.q[2], cnt.q[2:1]. The block `board` is the
           board: board.sw[1:0], board.btn[3:0], board.led[2:0] and board.pad<N>.

{"bd": 1, "name": "demo",
 "blocks": [{"id": "cnt", "kind": "ip", "type": "counter", "params": {"W": 3}, "x": 240, "y": 80}],
 "wires":  [{"src": "board.sw[1]", "dst": "cnt.en"}, {"src": "cnt.q", "dst": "board.led"}]}

generate() writes bd/<name>_wrapper.v, a module with the examples' ports (clk, sw[1:0],
btn[3:0], led[2:0]) plus one port per pad used. A design on the board's switches, buttons
and LEDs therefore needs no pin file and keeps the model check of `./bob build`; one that
uses a pad gets constrs/<name>.pcf with every port bit named, as vpr_run.read_pcf() wants.

Rules (validate()), each reported against the endpoint it is about:
  - every block input bit is driven exactly once (tie an unused one to a `const` block)
  - a wire's two ends are the same width
  - a source is a block output or a board input; a destination a block input or a board output
  - a `clk` port is never wired: the fabric has one clock and it reaches every `clk` port
  - a pad is used in one direction only, and not a pad the board already names (use sw/btn/led)
    nor the one the clock takes
  - LED bits nobody drives are tied to 0

Where this diverges from Vivado: no interfaces (AXI and the like: the fabric has none), no
address editor, no clock/reset wizards (one clock, synchronous resets only), and loops of
combinational logic through blocks are left to synthesis to report rather than found here.
"""

import json
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "software", "host"))

import bitstream as B  # noqa: E402
import project as P  # noqa: E402

VERSION = 1
MARK = "generated by bob from"          # first line of every wrapper: never read back as a module
BOARD = {"sw": ("input", 2), "btn": ("input", 4), "led": ("output", 3)}
BOARD_PADS = set(B.BOARD_IN) | set(B.BOARD_OUT)
# vpr_run.write_eblif gives clk the first pad the board does not name, so that one is taken
CLK_PAD = sorted(p for p in B.PAD_XY if p not in BOARD_PADS)[0]
FREE_PADS = sorted(p for p in B.PAD_XY if p not in BOARD_PADS and p != CLK_PAD)
ID = re.compile(r"[A-Za-z][A-Za-z0-9_]*")
# Verilog-2005 and SystemVerilog keywords (IEEE 1800 Annex B): a block name becomes an
# instance name in the wrapper, so none of these, and none of the wrapper's own ports.
